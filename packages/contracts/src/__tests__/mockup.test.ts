import { describe, expect, it } from 'vitest';

import {
  detectImageType,
  imageDimensions,
  jpegDimensions,
  markerMatchesKey,
  markerSchema,
  normalizeMarker,
  pngDimensions,
  svgDimensions,
  unsafeSvgReasons,
} from '../mockup';
import { jpeg, jpegBare, png } from './image-fixtures';

/**
 * Screen mockups: the geometry rules and the image gate.
 *
 * Every check in `decodeMockupImage` exists because the bytes it accepts are later handed back to a
 * browser under a `content-type` *this* code decides. So the tests drive it with the things a caller
 * could actually send — a truncated PNG, a text file wearing an image mime type, an SVG with a script
 * tag — rather than with well-formed fixtures only.
 */

describe('marker geometry', () => {
  it('accepts a point inside the image', () => {
    expect(markerSchema.safeParse({ key: 'checkout.title', x: 0.5, y: 0.1 }).success).toBe(true);
  });

  it('rejects a rectangle that runs off the right edge', () => {
    const result = markerSchema.safeParse({ key: 'a', x: 0.9, y: 0.1, width: 0.2 });
    expect(result.success).toBe(false);
    if (!result.success) expect(result.error.issues[0]!.message).toContain('0..1');
  });

  it('rejects a rectangle that runs off the bottom', () => {
    expect(markerSchema.safeParse({ key: 'a', x: 0.1, y: 0.95, height: 0.2 }).success).toBe(false);
  });

  it('rejects pixel coordinates, the mistake a caller makes when it measured the image', () => {
    // 240 is a perfectly ordinary x in pixels; as a fraction it is off the screen.
    expect(markerSchema.safeParse({ key: 'a', x: 240, y: 88 }).success).toBe(false);
  });

  it('normalises absent optionals to null, so the stored shape is the same either way', () => {
    expect(normalizeMarker({ key: 'a', x: 0.1, y: 0.2, namespace: '' })).toEqual({
      key: 'a',
      namespace: '',
      x: 0.1,
      y: 0.2,
      width: null,
      height: null,
    });
  });

  it('matches a marker to a key by key and namespace, because that is what a marker records', () => {
    expect(markerMatchesKey({ key: 'a', namespace: '' }, 'a')).toBe(true);
    expect(markerMatchesKey({ key: 'a', namespace: 'Localizable' }, 'a', 'Localizable')).toBe(true);
    expect(markerMatchesKey({ key: 'a', namespace: 'Localizable' }, 'a', '')).toBe(false);
    expect(markerMatchesKey({ key: 'a', namespace: '' }, 'b')).toBe(false);
  });
});

describe('image type detection', () => {
  it('reads the format from the bytes', () => {
    expect(detectImageType(new Uint8Array(png(4, 4)))).toBe('image/png');
    expect(detectImageType(new Uint8Array(jpeg(4, 4)))).toBe('image/jpeg');
    expect(detectImageType(new TextEncoder().encode('<svg viewBox="0 0 4 4"></svg>'))).toBe('image/svg+xml');
    // A BOM and an XML prolog are both normal for a file written by a tool.
    expect(detectImageType(new TextEncoder().encode('﻿<?xml version="1.0"?>\n<svg width="4" height="4"/>'))).toBe(
      'image/svg+xml',
    );
  });

  it('sees past a comment or a DOCTYPE, which is how design tools open an exported file', () => {
    // Both were refused as "Unrecognised image … WebP is not accepted" before: only a file starting
    // with `<svg` or with `<?xml` and then `<svg` was recognised, and the two prologue forms below are
    // at least as common as those two.
    expect(detectImageType(new TextEncoder().encode('<!-- Generated by exporter -->\n<svg width="4" height="4"/>'))).toBe(
      'image/svg+xml',
    );
    expect(
      detectImageType(new TextEncoder().encode('<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "x.dtd">\n<svg/>')),
    ).toBe('image/svg+xml');
  });

  it('still refuses a text file that merely mentions <svg>', () => {
    expect(detectImageType(new TextEncoder().encode('here is how you write <svg> in a README'))).toBeNull();
    expect(detectImageType(new TextEncoder().encode('# <svg viewBox="0 0 1 1">'))).toBeNull();
  });

  it('refuses what it does not understand, including WebP, whose dimensions it cannot read', () => {
    expect(detectImageType(new TextEncoder().encode('hello'))).toBeNull();
    const webp = new Uint8Array([0x52, 0x49, 0x46, 0x46, 0, 0, 0, 0, 0x57, 0x45, 0x42, 0x50]);
    expect(detectImageType(webp)).toBeNull();
  });
});

describe('dimensions', () => {
  it('reads PNG dimensions from IHDR', () => {
    expect(pngDimensions(new Uint8Array(png(1920, 1080)))).toEqual({ width: 1920, height: 1080 });
  });

  it('reads JPEG dimensions by walking to the start-of-frame, past segments that are not frames', () => {
    // Both fixtures carry the same dimensions; one has an APP0 in front of the frame. A reader that
    // assumes the frame is the first thing after SOI passes on the bare one and fails on every real
    // screenshot, so both are driven here.
    expect(jpegDimensions(new Uint8Array(jpeg(800, 600)))).toEqual({ width: 800, height: 600 });
    expect(jpegDimensions(new Uint8Array(jpegBare(800, 600)))).toEqual({ width: 800, height: 600 });
  });

  it('returns null rather than guessing when the file is not what it claims', () => {
    expect(jpegDimensions(new Uint8Array(png(4, 4)))).toBeNull();
    expect(pngDimensions(new Uint8Array(jpeg(4, 4)))).toBeNull();
    expect(jpegDimensions(new Uint8Array([0xff, 0xd8, 0xff, 0xc0, 0x00, 0x02]))).toBeNull();
  });

  it('prefers a viewBox over width/height for SVG, because that is the coordinate system markers use', () => {
    expect(svgDimensions('<svg width="300" height="200" viewBox="0 0 375 667"></svg>')).toEqual({ width: 375, height: 667 });
    expect(svgDimensions('<svg width="300" height="200"></svg>')).toEqual({ width: 300, height: 200 });
    expect(svgDimensions('<svg></svg>')).toBeNull();
  });

  it('reads only the root element, so an attribute that ends in "width" is not the image width', () => {
    // `stroke-width="2"` on the root used to win: `\bwidth=` treats the hyphen as a word boundary, so a
    // 375×667 sketch was stored as 2×667 and the editor then sized its box from a 2/667 ratio — the
    // sketch and every marker collapsed into a sliver.
    expect(svgDimensions('<svg stroke-width="2" width="375" height="667"></svg>')).toEqual({ width: 375, height: 667 });
    expect(svgDimensions('<svg stroke-width="2" viewBox="0 0 375 667"></svg>')).toEqual({ width: 375, height: 667 });
  });

  it('reads the root tag past a ">" inside a quoted attribute, so the size cap still applies', () => {
    // `[^>]*` stops at the first `>`, even inside a quoted value, which is legal SVG. The attributes
    // after it disappear — including the size — and with no size the 8192 cap is skipped entirely.
    const sketch = '<svg data-note="a > b" width="20000" height="20000"><rect width="1" height="1"/></svg>';
    expect(svgDimensions(sketch)).toEqual({ width: 20000, height: 20000 });
  });

  it('is recognised as an SVG even when its root element follows a long prologue', () => {
    // The detector and the measurer used to read different slice lengths (4 KB vs 8 KB), so a file
    // with a comment in between was an image to one and unmeasurable to the other.
    const prologue = '<!-- ' + 'x'.repeat(5000) + ' -->';
    const bytes = new TextEncoder().encode(`${prologue}<svg width="32" height="16"/>`);
    expect(detectImageType(bytes)).toBe('image/svg+xml');
    expect(imageDimensions(bytes, 'image/svg+xml')).toEqual({ width: 32, height: 16 });
  });

  it('is not fooled by a child element that has a size of its own', () => {
    // A sketch drawn as `<svg><rect width="300" height="150"/>…` has no intrinsic size of its own; the
    // first child's box is not it, and reporting one made the editor reserve the wrong space.
    expect(svgDimensions('<svg xmlns="http://www.w3.org/2000/svg"><rect width="327" height="48"/></svg>')).toBeNull();
  });

  it('dispatches by type', () => {
    const bytes = new Uint8Array(png(10, 20));
    expect(imageDimensions(bytes, 'image/png')).toEqual({ width: 10, height: 20 });
    expect(imageDimensions(bytes, 'image/svg+xml')).toBeNull();
  });
});

describe('unsafe SVG constructs', () => {
  it.each([
    ['<svg><script>alert(1)</script></svg>', '<script>'],
    ['<svg><foreignObject><body/></foreignObject></svg>', '<foreignObject>'],
    ['<svg onload="alert(1)"></svg>', '事件属性'],
    ['<svg><a href="javascript:alert(1)"></a></svg>', 'javascript:'],
    // A namespace prefix is the same element to a browser and was invisible to the unprefixed
    // patterns. Verified in headless Chrome against the running stack: this file's script executed
    // once its bytes were opened as a document.
    ['<svg xmlns:svg="http://www.w3.org/2000/svg"><svg:script>alert(1)</svg:script></svg>', '<script>'],
    ['<svg xmlns:x="http://www.w3.org/2000/svg"><x:foreignObject><body/></x:foreignObject></svg>', '<foreignObject>'],
    ['<?xml version="1.0"?><!DOCTYPE svg [<!ENTITY xxe SYSTEM "file:///etc/passwd">]><svg/>', 'XML 实体'],
  ])('names the construct to remove in %s', (svg, expected) => {
    expect(unsafeSvgReasons(svg).join(' ')).toContain(expected);
  });

  it('passes a sketch that only draws', () => {
    const svg = '<svg viewBox="0 0 100 100"><rect x="1" y="1" width="20" height="10"/><text x="2" y="8">Hi</text></svg>';
    expect(unsafeSvgReasons(svg)).toEqual([]);
  });
});
