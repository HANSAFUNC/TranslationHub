#!/usr/bin/env python3
"""Append RLS policies for tenant tables to a Prisma migration.

Usage:
    python3 scripts/append-rls.py packages/database/prisma/migrations/<migration-dir>

Every new table that stores tenant data needs:
  - organization_id column
  - ENABLE ROW LEVEL SECURITY + tenant_isolation policy

The script is idempotent: running it twice does not duplicate the statements.
"""
import re
import sys
from pathlib import Path

TENANT_TABLES = {
    "memberships", "projects", "project_members", "locales", "project_platforms", "namespaces",
    "translation_keys", "source_versions", "translation_entries", "translation_versions",
    "review_tasks", "review_actions", "glossary_terms", "translation_memory_entries",
    "repository_connections", "repository_file_mappings", "sync_scans", "sync_sessions",
    "sync_items", "sync_baselines", "sync_plans", "sync_conflicts", "sync_apply_reports",
    "project_events", "mcp_clients", "audit_logs", "qa_rules", "qa_runs", "qa_issues",
    "ai_provider_configs", "skills", "releases", "release_snapshots",
    "screen_mockups", "screen_mockup_markers",
}

HEADER = """
-- ===========================================================================
-- Row level security for tenant scoped tables (generated by scripts/append-rls.py).
-- The application role is not the table owner, so these policies are enforced.
-- ===========================================================================
CREATE OR REPLACE FUNCTION current_organization_id() RETURNS uuid
LANGUAGE sql STABLE AS $$
  SELECT NULLIF(current_setting('app.current_org_id', true), '')::uuid
$$;

CREATE OR REPLACE FUNCTION rls_bypassed() RETURNS boolean
LANGUAGE sql STABLE AS $$
  SELECT current_setting('app.bypass_rls', true) = 'on'
$$;
"""


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    migration = Path(sys.argv[1]) / "migration.sql"
    if not migration.exists():
        print(f"not found: {migration}")
        return 1
    sql = migration.read_text()
    created = set(re.findall(r'CREATE TABLE "([a-z_]+)"', sql))
    targets = sorted(created & TENANT_TABLES)
    if not targets:
        print("no tenant tables in this migration")
        return 0

    out = [HEADER]
    for table in targets:
        if f'ON "{table}"' in sql and "tenant_isolation" in sql.split(f'ALTER TABLE "{table}"')[-1][:400]:
            continue
        out.append(f'''
ALTER TABLE "{table}" ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON "{table}";
CREATE POLICY tenant_isolation ON "{table}"
  USING (organization_id = current_organization_id() OR rls_bypassed())
  WITH CHECK (organization_id = current_organization_id() OR rls_bypassed());''')
    out.append("""
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO localehub_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO localehub_app;
""")
    migration.write_text(sql + "\n".join(out))
    print(f"appended RLS policies for {len(targets)} table(s): {', '.join(targets)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
